#!/usr/bin/env python3
"""Bundle cached Cargo licenses and the installed Rust standard-library notices.

Run `cargo fetch --locked` once, then generation is offline. --check checks the
committed crate bundle against Cargo.lock; release builds regenerate the output
with their own compiler's standard-library notices.
"""

import argparse
import hashlib
from html.parser import HTMLParser
import json
from pathlib import Path
import re
import subprocess
import sys


ROOT = Path(__file__).resolve().parent.parent
RUST_MARKER = "\n===== Rust standard library =====\n"
LICENSE_PREFIXES = ("license", "licence", "copying", "notice", "copyright", "authors")


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def header():
    return (
        "Third-party notices for YLCC\n"
        "Generated by scripts/generate-notices.py; do not edit.\n"
        f"Cargo.lock SHA256: {sha256(ROOT / 'Cargo.lock')}\n"
        f"Generator SHA256: {sha256(Path(__file__))}\n\n"
        "This bundle includes all locked crates, including optional/build/target dependencies.\n"
        "Their original license choices and additional notices are retained below.\n"
        "For r-efi, the MIT option is used. YLCC's own license is in LICENSE.\n"
    )


def crate_notices():
    metadata = json.loads(subprocess.check_output(
        ["cargo", "metadata", "--locked", "--offline", "--format-version", "1"], cwd=ROOT))
    packages = sorted((p for p in metadata["packages"] if p["source"] is not None),
                      key=lambda p: (p["name"], p["version"], p["source"]))
    sections = [header()]
    for package in packages:
        directory = Path(package["manifest_path"]).parent
        files = sorted(path for path in directory.rglob("*") if path.is_file()
                       and path.name.lower().startswith(LICENSE_PREFIXES))
        if package.get("license_file"):
            files = sorted(set(files) | {directory / package["license_file"]})
        if not files:
            raise ValueError(f"No packaged license/notice files: {package['name']} {package['version']}")
        sections.append(f"\n===== {package['name']} {package['version']} =====\n"
                        f"License expression: {package.get('license') or 'see files below'}\n"
                        f"Source: {package['source']}\n")
        for path in files:
            # Relative filenames only: no workstation/cache paths enter the artifact.
            sections.append(f"\n--- {path.relative_to(directory).as_posix()} ---\n")
            sections.append(path.read_text(encoding="utf-8").rstrip() + "\n")
    return "".join(sections)


class RustText(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.parts = []
        self.skip = 0

    def handle_starttag(self, tag, attrs):
        if tag in ("style", "script"):
            self.skip += 1
        if not self.skip and tag in ("p", "pre", "br", "summary", "h1", "h2", "li"):
            self.parts.append("\n")

    def handle_endtag(self, tag):
        if tag in ("style", "script"):
            self.skip -= 1
        elif not self.skip and tag in ("p", "pre", "summary", "h1", "h2", "li"):
            self.parts.append("\n")

    def handle_data(self, data):
        if not self.skip:
            self.parts.append(data)


def rust_notices():
    sysroot = Path(subprocess.check_output(["rustc", "--print", "sysroot"], text=True).strip())
    document = sysroot / "share/doc/rust/COPYRIGHT-library.html"
    if not document.is_file():
        raise ValueError("Rust standard-library notices are missing; install the rust-docs component")
    parser = RustText()
    parser.feed(document.read_text(encoding="utf-8"))
    content = "".join(parser.parts)
    # Strip HTML layout indentation outside preformatted license text only at blank lines.
    content = re.sub(r"\n[ \t]+\n", "\n\n", content)
    content = re.sub(r"\n{3,}", "\n\n", content).strip()
    compiler = subprocess.check_output(["rustc", "--version"], text=True).strip()
    return RUST_MARKER + compiler + "\nSource: Rust toolchain share/doc/rust/COPYRIGHT-library.html\n\n" + content + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify the committed crate bundle is current (offline)")
    parser.add_argument("--output", type=Path, default=ROOT / "THIRD_PARTY_NOTICES.txt")
    args = parser.parse_args()
    if args.check:
        existing = args.output.read_text(encoding="utf-8")
        if existing.split(RUST_MARKER, 1)[0] != crate_notices() or RUST_MARKER not in existing:
            raise ValueError("Third-party crate notices are stale; run scripts/generate-notices.py")
        print("Third-party crate notices match Cargo.lock.")
    else:
        args.output.write_text(crate_notices() + rust_notices(), encoding="utf-8")
        print(f"Generated {args.output.name}.")


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        print(f"Notice generation failed: {error}", file=sys.stderr)
        sys.exit(1)
